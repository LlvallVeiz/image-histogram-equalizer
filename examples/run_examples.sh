#!/usr/bin/env bash
# run_examples.sh -- Regenerate the example images, run HE and CLAHE on
# each, and write the before/after statistics into RESULTS.md.
# All numbers in RESULTS.md come from real runs of the built binary.
set -euo pipefail
cd "$(dirname "$0")/.."

make ihe
python3 examples/generate_examples.py

OUTDIR=examples/outputs
mkdir -p "$OUTDIR"

for img in gradient low_contrast bimodal checker dark; do
  ./ihe he    "examples/${img}.pgm" "${OUTDIR}/${img}_he.pgm"    > /dev/null
  ./ihe clahe "examples/${img}.pgm" "${OUTDIR}/${img}_clahe.pgm" --tiles 8x8 --clip 2.0 > /dev/null
done

{
  echo "# Example results (generated by examples/run_examples.sh)"
  echo ""
  echo "Each example image (128x128, synthetic PGM) was processed with"
  echo "global histogram equalization (\`he\`) and with CLAHE"
  echo "(\`clahe --tiles 8x8 --clip 2.0\`). Statistics below are the real"
  echo "output of \`ihe compare\` on the generated files."
  echo ""
  for img in gradient low_contrast bimodal checker dark; do
    echo "## ${img}"
    echo ""
    echo '```'
    ./ihe compare "examples/${img}.pgm" "${OUTDIR}/${img}_he.pgm"
    echo '```'
    echo ""
    echo '```'
    ./ihe compare "examples/${img}.pgm" "${OUTDIR}/${img}_clahe.pgm"
    echo '```'
    echo ""
  done
} > examples/RESULTS.md

echo "Examples regenerated; results in examples/RESULTS.md"
